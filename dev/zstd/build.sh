#!/usr/bin/env bash
#
# Builds the zstd + ZDICT WebAssembly module used by the zstd payload codec.
#
# This is NOT part of `npm run build`. The output (dev/vendor/zstd/zstd.js) is committed, so a normal
# build/test/CI run needs neither emscripten nor network access; `npm run build:libs` just copies it
# into ext/lib/. Re-run this only to upgrade zstd or change the build flags, and commit the result.
#
# Requires: emscripten (brew install emscripten), curl, shasum.
# Usage: npm run build:zstd
#
# Why a custom build: off-the-shelf zstd WASM packages (@bokuweb/zstd-wasm, zstd-codec) expose
# compression with a *pre-existing* dictionary but omit ZDICT_trainFromBuffer, the dictionary
# *trainer*. Training is the whole point here -- an untrained dictionary leaves a large part of the
# compression on the table. See plan/zstd/README.md.

set -euo pipefail

ZSTD_VERSION="1.5.7"
# sha256 of the official release tarball (github.com/facebook/zstd/releases). Verified on download;
# the build refuses to run on a mismatch.
ZSTD_SHA256="eb33e51f49a15e023950cd7825ca74a4a2b43db8354825ac24fc1b7ee09e6fa3"

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "${script_dir}/../.." && pwd)"
build_dir="${script_dir}/.build"
out_dir="${repo_root}/dev/vendor/zstd"
tarball="${build_dir}/zstd-${ZSTD_VERSION}.tar.gz"
src_dir="${build_dir}/zstd-${ZSTD_VERSION}"

if ! command -v emcc >/dev/null 2>&1; then
    echo "error: emcc not found. Install emscripten (brew install emscripten) and retry." >&2
    exit 1
fi

mkdir -p "${build_dir}" "${out_dir}"

# --- fetch + verify -----------------------------------------------------------------------------
if [ ! -f "${tarball}" ]; then
    echo "==> downloading zstd ${ZSTD_VERSION}"
    curl -fsSL -o "${tarball}" \
        "https://github.com/facebook/zstd/releases/download/v${ZSTD_VERSION}/zstd-${ZSTD_VERSION}.tar.gz"
fi

echo "==> verifying checksum"
actual="$(shasum -a 256 "${tarball}" | cut -d' ' -f1)"
if [ "${actual}" != "${ZSTD_SHA256}" ]; then
    echo "error: checksum mismatch for ${tarball}" >&2
    echo "  expected ${ZSTD_SHA256}" >&2
    echo "  actual   ${actual}" >&2
    echo "  refusing to build; delete the file and retry, or update ZSTD_SHA256 for a new version." >&2
    exit 1
fi

if [ ! -d "${src_dir}" ]; then
    echo "==> extracting"
    mkdir -p "${src_dir}"
    tar xzf "${tarball}" -C "${src_dir}" --strip-components=1
fi

# --- build --------------------------------------------------------------------------------------
# huf_decompress_amd64.S is x86-only asm, so it is excluded and ZSTD_DISABLE_ASM turns on the
# portable C path. Multithreading is off (no pthreads in the extension worker) and DYNAMIC_BMI2 is
# off (runtime CPU feature detection is meaningless for wasm).
sources=$(find "${src_dir}/lib/common" "${src_dir}/lib/compress" "${src_dir}/lib/decompress" \
    "${src_dir}/lib/dictBuilder" -name '*.c' | sort | tr '\n' ' ')

echo "==> compiling $(echo "${sources}" | wc -w | tr -d ' ') zstd sources + shim.c"

# SINGLE_FILE embeds the wasm inside the .js, costing ~8% (502 KB, vs 464 KB split as 10 KB glue +
# 454 KB wasm) and buying:
#   1. one artifact to commit, vendor and copy;
#   2. Safari serves extension .wasm without the application/wasm MIME, which breaks
#      instantiateStreaming -- embedding sidesteps the fallback path entirely;
#   3. no runtime path resolution for a sibling .wasm (which bit the sqlite vendoring).
# Instantiation from an ArrayBuffer is allowed by the extension CSP's 'wasm-unsafe-eval'.
# It does NOT keep a binary out of git: emscripten embeds an escaped binary string rather than
# base64, so the output holds NUL/high bytes. .gitattributes marks it -text accordingly.
emcc -O3 \
    -DZSTD_MULTITHREAD=0 \
    -DZSTD_DISABLE_ASM=1 \
    -DDYNAMIC_BMI2=0 \
    -DZDICT_STATIC_LINKING_ONLY \
    -I "${src_dir}/lib" \
    -I "${src_dir}/lib/common" \
    -I "${src_dir}/lib/dictBuilder" \
    ${sources} "${script_dir}/shim.c" \
    -o "${out_dir}/zstd.js" \
    -sMODULARIZE=1 \
    -sEXPORT_ES6=1 \
    -sEXPORT_NAME=zstdInitModule \
    -sENVIRONMENT=web,worker,node \
    -sALLOW_MEMORY_GROWTH=1 \
    -sFILESYSTEM=0 \
    -sSINGLE_FILE=1 \
    -sEXPORTED_FUNCTIONS='_yz_train,_yz_cdict_create,_yz_cdict_free,_yz_ddict_create,_yz_ddict_free,_yz_compress,_yz_decompress,_yz_compress_bound,_yz_frame_content_size,_malloc,_free' \
    -sEXPORTED_RUNTIME_METHODS='HEAPU8,HEAPU32'

# The file is committed and reachable from the tsc project graph via the codec's dynamic import, so
# it needs the same @ts-nocheck banner the esbuild-bundled libs get (decision #12). eslint skips it
# via the dev/vendor/ ignore rather than an in-file directive.
tmp="${out_dir}/.zstd.js.tmp"
{
    echo "// @ts-nocheck"
    echo "// Generated by dev/zstd/build.sh from zstd ${ZSTD_VERSION}. Do not edit."
    cat "${out_dir}/zstd.js"
} > "${tmp}"
mv "${tmp}" "${out_dir}/zstd.js"

echo "==> wrote ${out_dir}/zstd.js ($(du -h "${out_dir}/zstd.js" | cut -f1))"
echo "    commit it; 'npm run build:libs' copies it into ext/lib/."
